import { generateAIContent } from "../utils/aiProvider.js";
import extractResumeText from "../utils/resumeParser.js";

export const analyzeResume = async (req, res) => {
    try {
        const file = req.file;

        if (!file) {
            return res.status(400).json({
                message: "Resume file is required.",
                success: false,
            });
        }

        const resumeText =
            await extractResumeText(file.buffer);

        const prompt = `
You are an expert technical recruiter.

Analyze the following resume and extract the candidate's information.

Resume:
${resumeText}

Return ONLY valid JSON in exactly this structure:

{
    "skills": [],
    "projects": [],
    "experience": [],
    "education": []
}

Rules:
1. skills must contain technical skills mentioned in the resume.
2. projects must contain the names of technical projects.
3. experience must contain the candidate's work/internship experience.
4. education must contain the candidate's education.
5. Do not invent information.
6. Return only JSON. Do not use markdown.
`;

        // Gemini first -> Groq fallback
        const response =
            await generateAIContent(prompt);

        console.log(
            `RESUME ANALYSIS GENERATED BY: ${response.provider}`
        );

        return res.status(200).json({
            success: true,
            data: response.text,
        });
    } catch (error) {
        console.log(
            "RESUME AI ERROR:",
            error
        );

        return res.status(500).json({
            message:
                "Resume analysis failed.",
            success: false,
        });
    }
};